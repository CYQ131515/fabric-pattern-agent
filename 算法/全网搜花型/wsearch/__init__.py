"""全网搜花型 —— 按用户需求在全网找**真正能四方连续铺开**的花型图。

一句话流程
    用户的一句话
      → analyze  用大模型把它变成一组"能命中平铺图"的检索词（中英各半）
      → providers 并发打多家图片搜索/图库 API，收回来一堆图片直链
      → fetch    并发下载，**逐张跑平铺判定**，只留铺得开的
      → rank     按平铺质量排序、感知哈希去重、压住单一来源的垄断
      → store    落成和本地花型库一样的形状（orig/ thumb/ index.json）

三段是分开的，任何一段都能单独用
    from wsearch import tile
    tile.analyze("a.jpg")          # 就判这一张能不能平铺
    tile.is_tile("a.jpg")          # 只要一个是/否

为什么要有这个算法
    光靠本地花型库，能满足的需求上限就是"库里已经有的"。客户提一个
    "莫兰迪灰调的抽象笔触，做衬衫"，库里没有就只能现场生图。全网搜是
    第三条路：**先在真实存在的图里找，找不到再花钱生成** —— 快、便宜、
    而且客户看到的都是真做过的样式。
"""
