def load_vocab(path=None):
    """读词表。给了路径（比如主程序的 后端/data/vocab.json）就用它的，
    否则用内置默认。

    合并规则是**逐维覆盖**而不是整体替换：主程序的 vocab.json 只定义了
    四维各 8 个值，这里的默认词表每维 12 个。如果整体替换，主程序那份
    一变少我们这边也跟着变少；逐维覆盖则"以主程序为准，它没说的维度
    沿用默认"。这样两边不会打架。
    """
    vocab = {d: list(DEFAULT_VOCAB[d]) for d in DIMS}
    if not path:
        return vocab
    try:
        with open(path, encoding='utf-8') as f:
            data = json.load(f)
    except (OSError, ValueError):
        return vocab
    if not isinstance(data, dict):
        return vocab

    # 允许直接给 {"style": [...], ...}，也允许包一层 {"vocab": {...}}
    src = data.get('vocab') if isinstance(data.get('vocab'), dict) else data
    for dim in DIMS:
        vals = src.get(dim)
        if isinstance(vals, list) and vals:
            vocab[dim] = [str(v).strip() for v in vals if str(v).strip()]
    return vocab


def add_extra(vocab, extra):
    """在词表上追加自定义值（--extra-style 这类参数用）。

    extra 形如 {'style': ['暗黑学院'], ...}，追加时去重、保序。
    """
    out = {d: list(vocab.get(d) or []) for d in DIMS}
    for dim, vals in (extra or {}).items():
        if dim not in out:
            continue
        for v in (vals or []):
            v = str(v).strip()
            if v and v not in out[dim]:
                out[dim].append(v)
    return out


def normalize_one(value, dim, vocab):
    """把一个自由说法归到词表里的唯一值；归不上返回 None。

    判断顺序（跟 core/vision.py 一致，都是踩过才定的）：
      1. 完全相等 —— 最稳；
      2. **先检查是不是同时提到了多个词表值** —— 这是必须放在别名之前的
         一道闸。"花卉与几何混合"这种句子，别名表里的单字别名"花"会
         一把命中并归成"花卉"，把"几何"吃掉。先判歧义就不会。
         （别名表里允许有"花"这种宽泛说法，正是因为它对"客户只说了花的"
          有用 —— 用歧义检查兜住它的副作用，比删掉它更好。）
      3. 别名表 —— 口语说法优先于包含匹配，否则"美式复古"会被
         "复古"这个别名抢先命中；
      4. 双向包含 —— 模型说"蓝白"→"蓝白青花"，或说"蓝白青花感"→"蓝白青花"。
         只有**唯一命中**才算，命中多个说明有歧义，交给 free。
    """
    if value is None:
        return None
    s = str(value).strip()
    if not s:
        return None

    vals = vocab.get(dim) or []
    if s in vals:
        return s

    # 同时提到两个及以上词表值 → 有歧义，不猜，留给 free 让人看
    if len([v for v in vals if v in s]) > 1:
        return None

    for alias, canon in (ALIASES.get(dim) or {}).items():
        if alias in s and canon in vals:
            return canon

    hits = [v for v in vals if v in s or (len(v) > 2 and s in v)]
    return hits[0] if len(hits) == 1 else None


def normalize_many(values, dim, vocab, limit=MAX_PER_DIM):
    """多值归一。

    返回 (hit, free)：
        hit  —— 归到词表内的值，去重、保序、最多 limit 条；
        free —— 归不上的原话，去重、保序。

    free 不做条数截断（它本来就不参与检索，只给人看和做新词发现），
    但会在写盘时原样保留。
    """
    hit, free, seen = [], [], set()
    for v in _as_list(values):
        if v in seen:
            continue
        seen.add(v)
        canon = normalize_one(v, dim, vocab)
        if canon:
            if canon not in hit and len(hit) < limit:
                hit.append(canon)
        else:
            if v not in free:
                free.append(v)
    return hit, free


def _as_list(val):
    """把模型返回的东西统一成字符串列表。

    模型很爱把数组写成字符串（"花卉、叶片"或"花卉,叶片"），也可能
    真返回数组，甚至给个 dict。这里全部抹平。
    """
    if val is None:
        return []
    if isinstance(val, dict):
        # 少见但出现过：{"1": "花卉", "2": "几何"}
        val = list(val.values())
    if isinstance(val, (list, tuple, set)):
        parts = []
        for x in val:
            parts.extend(_split_scalar(x))
    else:
        parts = _split_scalar(val)
    out = []
    for p in parts:
        p = p.strip().strip('"\'·。、,，;；')
        if p and p not in out:
            out.append(p)
    return out


def _split_scalar(x):
    """标量 → 片段。只按明确的分隔符拆，**不按空格拆** ——
    "蓝白青花"这种没有空格，但"Y2K 未来"有；按空格拆会把一个词拆成两个。
    所以这里只认顿号、逗号、分号、斜杠、竖线。"""
    import re
    if x is None:
        return []
    if isinstance(x, (list, tuple, set)):
        out = []
        for y in x:
            out.extend(_split_scalar(y))
        return out
    s = str(x).strip()
    if not s:
        return []
    return [p for p in re.split(r'[、,，;；/|]+', s) if p.strip()]


def describe(vocab):
    """给页面/日志用的一句话摘要。"""
    return ' / '.join('%s %d 项' % (DIM_CN[d], len(vocab.get(d) or [])) for d in DIMS)
